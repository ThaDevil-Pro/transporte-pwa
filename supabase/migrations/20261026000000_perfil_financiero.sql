-- CAMIFY · Perfil Financiero
-- Un usuario de finanzas solo maneja el dinero de los alumnos:
--  · ve la lista de alumnos con su saldo (finanzas_alumnos)
--  · registra pagos y corrige saldos, incluido dejar saldo a favor
--    (admin_registrar_pago y admin_actualizar_saldo ahora aceptan Financiero)
--  · ve el historial de pagos y correcciones (finanzas_movimientos)
--  · ve el informe de gastos (admin_reporte_gastos)
-- No puede registrar ni editar usuarios, ver choferes, diésel, quejas ni la
-- bitácora completa. Lo da de alta un administrador, como a los demás.
-- Su sesión dura 24 horas, igual que la de administración.

-- 1. Tabla de usuarios de finanzas (misma protección que admins)
create table if not exists public.financieros (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  nombre text not null,
  usuario text not null unique,
  password text not null,
  debe_cambiar_password boolean not null default true
);
alter table public.financieros enable row level security;
revoke all on public.financieros from anon, authenticated;
drop trigger if exists trg_hash_password on public.financieros;
create trigger trg_hash_password before insert or update of password on public.financieros
  for each row execute function public._hash_password();

-- 2. Sesiones: nuevo rol y 24 horas como administración
alter table public.sesiones drop constraint if exists sesiones_rol_check;
alter table public.sesiones add constraint sesiones_rol_check
  check (rol in ('Estudiante', 'Chofer', 'Admin', 'Financiero'));

create or replace function privado.duracion_sesion()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.expira_en := now() + case when new.rol in ('Admin', 'Financiero') then interval '24 hours' else interval '7 days' end;
  return new;
end;
$$;

-- 3. Inicio de sesión
create or replace function public.login(p_rol text, p_identificador text, p_password text, p_dispositivo text default null)
returns json
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_ident text := trim(coalesce(p_identificador, ''));
  v_ip text := coalesce(privado.ip_cliente(), 'desconocida');
  v_cuenta text := coalesce(p_rol, '') || ':' || left(lower(v_ident), 40);
  v_disp text := case
    when p_dispositivo ~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
    then left(encode(extensions.digest(p_dispositivo, 'sha256'), 'hex'), 32)
  end;
  v_clave_dv text := 'dv:' || v_cuenta || ':' || coalesce(v_disp, '');
  v_clave_ua text := 'ua:' || v_cuenta || '@' || v_ip;
  v_clave_u text := 'u:' || v_cuenta;
  v_clave_ip text := 'ip:' || v_ip;
  v_conocido boolean := false;
  v_existe boolean;
  v_bloqueo timestamptz;
  v_perfil json;
  v_ref text;
  v_cambiar boolean;
  v_token uuid;
begin
  delete from sesiones where expira_en < now();
  delete from privado.login_intentos
   where (clave not like 'ok:%' and coalesce(bloqueado_hasta, primer_fallo) < now() - interval '1 day')
      or (clave like 'ok:%' and primer_fallo < now() - interval '60 days');

  if v_disp is not null then
    v_conocido := exists (select 1 from privado.login_intentos where clave = 'ok:' || v_cuenta || ':' || v_disp);
  end if;

  select max(bloqueado_hasta) into v_bloqueo
  from privado.login_intentos
  where bloqueado_hasta > now()
    and clave = any (case when v_conocido then array[v_clave_dv]
                          else array[v_clave_ua, v_clave_u, v_clave_ip] end);

  if v_bloqueo is not null then
    return json_build_object('bloqueado', true,
      'minutos', greatest(1, ceil(extract(epoch from v_bloqueo - now()) / 60))::int);
  end if;

  if octet_length(coalesce(p_password, '')) between 1 and 200 then
    if p_rol = 'Estudiante' then
      select matricula, json_build_object('nombre', nombre, 'matricula', matricula, 'saldo', saldo), debe_cambiar_password
        into v_ref, v_perfil, v_cambiar
      from alumnos where matricula = v_ident and password = crypt(p_password, password);
    elsif p_rol = 'Chofer' then
      select licencia, json_build_object('nombre', nombre, 'licencia', licencia), debe_cambiar_password
        into v_ref, v_perfil, v_cambiar
      from choferes where licencia = v_ident and password = crypt(p_password, password);
    elsif p_rol = 'Financiero' then
      select usuario, json_build_object('nombre', nombre, 'usuario', usuario), debe_cambiar_password
        into v_ref, v_perfil, v_cambiar
      from financieros where usuario = v_ident and password = crypt(p_password, password);
    elsif p_rol = 'Admin' then
      select usuario, json_build_object('usuario', usuario), debe_cambiar_password
        into v_ref, v_perfil, v_cambiar
      from admins where usuario = v_ident and password = crypt(p_password, password);
    end if;
  end if;

  if v_ref is null then
    v_existe := case p_rol
      when 'Estudiante' then exists (select 1 from alumnos where matricula = v_ident)
      when 'Chofer' then exists (select 1 from choferes where licencia = v_ident)
      when 'Financiero' then exists (select 1 from financieros where usuario = v_ident)
      when 'Admin' then exists (select 1 from admins where usuario = v_ident)
      else false
    end;
    -- Mismo tiempo de respuesta exista o no la cuenta: no revela qué identificadores existen
    if not v_existe and octet_length(coalesce(p_password, '')) between 1 and 200 then
      perform crypt(p_password, gen_salt('bf', 10));
    end if;
    if v_conocido then
      perform privado.registrar_fallo(v_clave_dv, 10);
    else
      perform privado.registrar_fallo(v_clave_ua, 5);
      perform privado.registrar_fallo(v_clave_u, 30);
      -- Solo los fallos sobre cuentas reales cuentan para la red, para que
      -- inventar usuarios no sirva para bloquear a toda una escuela
      if v_existe then
        perform privado.registrar_fallo(v_clave_ip, 300);
      end if;
    end if;
    return null;
  end if;

  delete from privado.login_intentos where clave in (v_clave_ua, v_clave_dv);
  if v_disp is not null then
    insert into privado.login_intentos (clave, fallos, primer_fallo)
    values ('ok:' || v_cuenta || ':' || v_disp, 0, now())
    on conflict (clave) do update set fallos = 0, primer_fallo = now(), bloqueado_hasta = null;
  end if;

  insert into sesiones (rol, usuario_ref, debe_cambiar)
  values (p_rol, v_ref, coalesce(v_cambiar, false))
  returning token into v_token;

  return json_build_object('token', v_token, 'perfil', v_perfil, 'debe_cambiar', coalesce(v_cambiar, false));
end;
$$;

-- 4. Cambio de contraseña: cada rol en su tabla (antes, lo que no era alumno
--    ni chofer se buscaba en admins)
create or replace function public.cambiar_password(p_token uuid, p_actual text, p_nueva text)
returns void
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_rol text;
  v_ref text;
  v_hash text;
begin
  select rol, usuario_ref into v_rol, v_ref
  from sesiones where token = p_token and expira_en > now();
  if v_ref is null then
    raise exception 'Sesión inválida o expirada' using errcode = '28000';
  end if;

  if v_rol = 'Estudiante' then select password into v_hash from alumnos where matricula = v_ref;
  elsif v_rol = 'Chofer' then select password into v_hash from choferes where licencia = v_ref;
  elsif v_rol = 'Financiero' then select password into v_hash from financieros where usuario = v_ref;
  elsif v_rol = 'Admin' then select password into v_hash from admins where usuario = v_ref;
  end if;

  if v_hash is null or v_hash <> crypt(coalesce(p_actual, ''), v_hash) then
    raise exception 'La contraseña actual no es correcta';
  end if;
  if p_nueva = p_actual then
    raise exception 'La nueva contraseña debe ser diferente a la actual';
  end if;
  perform privado.validar_password(p_nueva, v_ref);

  if v_rol = 'Estudiante' then
    update alumnos set password = privado.hash(p_nueva), debe_cambiar_password = false where matricula = v_ref;
  elsif v_rol = 'Chofer' then
    update choferes set password = privado.hash(p_nueva), debe_cambiar_password = false where licencia = v_ref;
  elsif v_rol = 'Financiero' then
    update financieros set password = privado.hash(p_nueva), debe_cambiar_password = false where usuario = v_ref;
  else
    update admins set password = privado.hash(p_nueva), debe_cambiar_password = false where usuario = v_ref;
  end if;

  -- Cierra las demás sesiones abiertas y libera esta
  delete from sesiones where rol = v_rol and usuario_ref = v_ref and token <> p_token;
  update sesiones set debe_cambiar = false where token = p_token;
  perform privado.log(v_rol, v_ref, 'cambio_password', '{}'::jsonb);
end;
$$;

-- 5. Administración de usuarios: el admin da de alta, edita y elimina financieros
create or replace function public.admin_usuarios(p_token uuid)
returns json
language plpgsql
security definer
set search_path = public
as $$
begin
  perform _validar_sesion(p_token, array['Admin']);
  return json_build_object(
    'alumnos',  coalesce((select json_agg(json_build_object('id', id, 'nombre', nombre, 'matricula', matricula, 'saldo', saldo) order by nombre) from alumnos), '[]'::json),
    'choferes', coalesce((select json_agg(json_build_object('id', id, 'nombre', nombre, 'licencia', licencia) order by nombre) from choferes), '[]'::json),
    'financieros', coalesce((select json_agg(json_build_object('id', id, 'nombre', nombre, 'usuario', usuario) order by nombre) from financieros), '[]'::json),
    'admins',   coalesce((select json_agg(json_build_object('id', id, 'usuario', usuario) order by usuario) from admins), '[]'::json)
  );
end;
$$;

do $$
declare
  -- [función, texto actual, texto nuevo]
  cambios text[][] := array[
    -- Alta
    array['public.admin_crear_usuario(uuid, text, text, text, text, numeric)',
      $a$  if p_rol not in ('Estudiante', 'Chofer', 'Admin') then$a$,
      $a$  if p_rol not in ('Estudiante', 'Chofer', 'Admin', 'Financiero') then$a$],
    array['public.admin_crear_usuario(uuid, text, text, text, text, numeric)',
      $a$  else
    insert into admins (usuario, password, debe_cambiar_password)$a$,
      $a$  elsif p_rol = 'Financiero' then
    insert into financieros (nombre, usuario, password, debe_cambiar_password)
    values (v_nombre, v_ident, privado.hash(p_password), true);
  else
    insert into admins (usuario, password, debe_cambiar_password)$a$],
    -- Edición: nombre y contraseña temporal (el usuario no cambia)
    array['public.admin_editar_usuario(uuid, text, text, text, text)',
      $a$  elsif p_rol = 'Admin' then
    select usuario into v_ref from admins where id = p_id::bigint;$a$,
      $a$  elsif p_rol = 'Financiero' then
    select usuario into v_ref from financieros where id = p_id::bigint;
    if v_ref is null then raise exception 'Usuario no encontrado'; end if;
    v_nuevo := privado.validar_nombre(p_nombre);
    update financieros set nombre = v_nuevo where id = p_id::bigint;
    if v_cambia_pw then
      perform privado.validar_password(p_password, v_ref);
      update financieros set password = privado.hash(p_password), debe_cambiar_password = true where id = p_id::bigint;
    end if;
  elsif p_rol = 'Admin' then
    select usuario into v_ref from admins where id = p_id::bigint;$a$],
    -- Baja
    array['public.admin_eliminar_usuario(uuid, text, text)',
      $a$  elsif p_rol = 'Admin' then
    select usuario into v_ref from admins where id = p_id::bigint;$a$,
      $a$  elsif p_rol = 'Financiero' then
    delete from financieros where id = p_id::bigint returning usuario, nombre into v_ref, v_nombre;
  elsif p_rol = 'Admin' then
    select usuario into v_ref from admins where id = p_id::bigint;$a$],
    -- Dinero de los alumnos: también finanzas, y la bitácora guarda quién fue
    array['public.admin_registrar_pago(uuid, uuid, numeric, text)',
      $a$_validar_sesion(p_token, array['Admin'])$a$,
      $a$_validar_sesion(p_token, array['Admin', 'Financiero'])$a$],
    array['public.admin_registrar_pago(uuid, uuid, numeric, text)',
      $a$privado.log('Admin', v_admin,$a$,
      $a$privado.log((select rol from sesiones where token = p_token), v_admin,$a$],
    array['public.admin_actualizar_saldo(uuid, uuid, numeric, text)',
      $a$_validar_sesion(p_token, array['Admin'])$a$,
      $a$_validar_sesion(p_token, array['Admin', 'Financiero'])$a$],
    array['public.admin_actualizar_saldo(uuid, uuid, numeric, text)',
      $a$privado.log('Admin', v_admin,$a$,
      $a$privado.log((select rol from sesiones where token = p_token), v_admin,$a$],
    array['public.admin_reporte_gastos(uuid, date, date)',
      $a$_validar_sesion(p_token, array['Admin'])$a$,
      $a$_validar_sesion(p_token, array['Admin', 'Financiero'])$a$]
  ];
  v text;
begin
  for i in 1 .. array_length(cambios, 1) loop
    v := replace(pg_get_functiondef(cambios[i][1]::regprocedure), E'\r\n', E'\n');
    -- Ya aplicado (el texto nuevo contiene al viejo en algunos casos: se revisa primero)
    continue when position(cambios[i][3] in v) > 0;
    if position(cambios[i][2] in v) = 0 then
      raise exception 'No se encontró el texto a cambiar en % (cambio %)', cambios[i][1], i;
    end if;
    execute replace(v, cambios[i][2], cambios[i][3]);
  end loop;
end $$;

-- 6. Lo que ve finanzas
create or replace function public.finanzas_alumnos(p_token uuid)
returns json
language plpgsql
security definer
set search_path = public
as $$
begin
  perform _validar_sesion(p_token, array['Admin', 'Financiero']);
  return coalesce((select json_agg(json_build_object('id', id, 'nombre', nombre, 'matricula', matricula, 'saldo', saldo) order by nombre)
                   from alumnos), '[]'::json);
end;
$$;

-- Pagos y correcciones de saldo, lo más reciente primero, con el nombre del alumno
create or replace function public.finanzas_movimientos(p_token uuid, p_limite integer default 150)
returns json
language plpgsql
security definer
set search_path = public
as $$
begin
  perform _validar_sesion(p_token, array['Admin', 'Financiero']);
  return coalesce((
    select json_agg(json_build_object('id', b.id, 'creado_en', b.creado_en, 'actor_rol', b.actor_rol, 'actor', b.actor,
                                      'accion', b.accion, 'detalle', b.detalle || jsonb_build_object('nombre', a.nombre))
                    order by b.id desc)
    from (select * from privado.bitacora
          where accion in ('pago_registrado', 'saldo_ajustado')
          order by id desc limit least(greatest(coalesce(p_limite, 150), 1), 300)) b
    left join alumnos a on a.matricula = b.detalle->>'matricula'
  ), '[]'::json);
end;
$$;

revoke all on function public.finanzas_alumnos(uuid) from public;
revoke all on function public.finanzas_movimientos(uuid, integer) from public;
grant execute on function public.finanzas_alumnos(uuid) to anon, authenticated;
grant execute on function public.finanzas_movimientos(uuid, integer) to anon, authenticated;
