create table if not exists public.alumnos (
  id uuid primary key default gen_random_uuid(), nombre text not null, matricula text not null unique,
  estado text default 'Activo', password text, saldo numeric(10,2) default 0.00);
create table if not exists public.choferes (
  id bigint generated by default as identity primary key, created_at timestamptz default now(),
  nombre text not null, licencia text not null unique, password text not null);
create table if not exists public.admins (
  id bigint generated by default as identity primary key, created_at timestamptz default now(),
  usuario text not null unique, password text not null);
create table if not exists public.historial_viajes (
  id bigint generated by default as identity primary key, matricula text not null,
  monto numeric not null default 30, fecha_hora timestamptz default now());
create table if not exists public.estado_viaje (
  id integer primary key, estado text not null default 'ESPERANDO', updated_at timestamptz default now(),
  tiempo_salida timestamptz, temporizador_activo boolean default false);
insert into public.estado_viaje (id) values (1) on conflict do nothing;
create table if not exists public.horarios_matriz (
  id bigint generated by default as identity primary key,
  lunes jsonb default '{"hora": "", "tipo": "IDA"}', martes jsonb default '{"hora": "", "tipo": "IDA"}',
  miercoles jsonb default '{"hora": "", "tipo": "IDA"}', jueves jsonb default '{"hora": "", "tipo": "IDA"}',
  viernes jsonb default '{"hora": "", "tipo": "IDA"}', created_at timestamptz not null default timezone('utc', now()));
create table if not exists public.abordajes (
  id bigint generated by default as identity primary key, nombre text not null, matricula text not null,
  created_at timestamptz not null default timezone('utc', now()));
